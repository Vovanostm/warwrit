ROOT = Path(__file__).resolve().parents[4]
APPROVED = [ROOT / "docs/wiki/economy-quests/m1-quest-texts.md"]


def main():
    failed = 0
    for path in APPROVED:
        issues = check(path.read_text(encoding="utf-8"))
        if issues:
            print(f"FAIL approved text has issues: {path.name}: {issues[:3]}")
            failed += 1
    for name, text in MUST_FLAG.items():
        if not check(text):
            print(f"FAIL must flag: {name}: {text[:60]}")
            failed += 1
    for name, text in MUST_PASS.items():
        issues = check(text)
        if issues:
            print(f"FAIL must pass: {name}: {issues}")
            failed += 1
    total = len(MUST_FLAG) + len(MUST_PASS) + len(APPROVED)
    print(f"{total - failed}/{total} passed")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
